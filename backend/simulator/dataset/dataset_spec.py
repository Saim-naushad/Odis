"""Immutable, JSON-(de)serializable specification for one dataset generation run.

`DatasetSpec` describes *policy* — which scenarios, how many runs of each,
seed assignment, operating-condition ranges, sensor noise, split
proportions — not already-resolved runs. `run_plan.plan_runs` turns a
`DatasetSpec` into a deterministic, ordered list of fully resolved
`RunConfig`s (via PR163's `RunTemplate`/`resolve_run_config`), with no
hidden randomness or wall-clock identity.

Hand-written (de)serialization, not a generic reflection/schema library —
the field set is small and stable, and an explicit reader/writer pair is
easier to audit than a dependency that would guess field types.
`from_json_dict` methods accept `dict[str, Any]` (parsed JSON is inherently
dynamically typed) and convert explicitly; `to_json_dict` methods return
`dict[str, object]`, since by construction their values are already
concrete.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from backend.simulator.dataset.fault_variation import (
    FaultSeverityRange,
    FaultTimingRange,
)
from backend.simulator.dataset.operating_conditions import (
    NoiseRegime,
    OperatingConditionRanges,
    SensorNoiseConfig,
)
from backend.simulator.dataset.parquet_schema import SCHEMA_VERSION
from backend.simulator.dataset.run_config import DatasetScenario

# Runs generated by this PR only ever inject a fault on one target asset at
# a time — see the repository audit's fault feasibility matrix. Sensor
# anomaly here means the existing bias-ramp behavior only.
_SUPPORTED_FAULT_SCENARIOS = frozenset(
    {
        DatasetScenario.COOLING_DEGRADATION,
        DatasetScenario.HYDROGEN_SUPPLY_ISSUE,
        DatasetScenario.SENSOR_ANOMALY,
    }
)


@dataclass(frozen=True)
class ScenarioRunSpec:
    """How many runs of one scenario/class to generate, and their shared
    fault timing/severity policy.

    Every run generated from one `ScenarioRunSpec` differs in seed (which
    resolves operating conditions, sensor noise, and — for the fields
    below — fault timing/severity draws) and target asset (round-robin over
    `DatasetSpec.target_asset_ids`). `fault_start_sim_seconds` and
    `fault_severity` each have two mutually exclusive representations:

    - a fixed scalar, shared identically by every run of this plan (the
      original PR161 behavior); or
    - a `..._range` (`FaultTimingRange` / `FaultSeverityRange`), sampled once
      per run from an isolated seed-derived RNG stream (see
      `run_template.resolve_run_config`) — so runs of the same class no
      longer share an identical fault onset and magnitude, which was the
      dataset's most severe trivial-separability risk.

    Exactly one of (fixed, range) must be set per field for a fault
    scenario; neither may be set for `normal_operation` (see
    `__post_init__`). `fault_duration_sim_seconds` has no ranged form in
    this PR — it stays a single fixed value per plan.
    """

    scenario_name: DatasetScenario
    run_count: int
    fault_start_sim_seconds: float | None = None
    fault_start_range: FaultTimingRange | None = None
    fault_duration_sim_seconds: float | None = None
    fault_severity: float | None = None
    fault_severity_range: FaultSeverityRange | None = None

    def __post_init__(self) -> None:
        if self.run_count <= 0:
            raise ValueError("run_count must be positive")

        has_fixed_start = self.fault_start_sim_seconds is not None
        has_start_range = self.fault_start_range is not None
        has_fixed_severity = self.fault_severity is not None
        has_severity_range = self.fault_severity_range is not None

        if has_fixed_start and has_start_range:
            raise ValueError(
                "cannot set both fault_start_sim_seconds and "
                "fault_start_range — one scenario plan must define a single "
                "fixed-or-ranged fault-timing policy"
            )
        if has_fixed_severity and has_severity_range:
            raise ValueError(
                "cannot set both fault_severity and fault_severity_range — "
                "one scenario plan must define a single fixed-or-ranged "
                "severity policy"
            )

        is_fault_scenario = self.scenario_name in _SUPPORTED_FAULT_SCENARIOS
        if is_fault_scenario:
            if not has_fixed_start and not has_start_range:
                raise ValueError(
                    f"{self.scenario_name} requires fault_start_sim_seconds "
                    "or fault_start_range"
                )
            if not has_fixed_severity and not has_severity_range:
                raise ValueError(
                    f"{self.scenario_name} requires fault_severity or "
                    "fault_severity_range"
                )
            # Field-level fault-window/severity consistency for the fixed
            # case (e.g. severity in [0, 1], window fits duration) is
            # enforced by RunConfig itself once resolved (see
            # run_plan.plan_runs) — duplicating that validation here would
            # be two sources of truth. A range's own bounds are validated by
            # FaultTimingRange/FaultSeverityRange; whether its candidates fit
            # `duration_sim_seconds` is validated by `DatasetSpec`, the first
            # place that value is known.
        else:
            if has_fixed_start or has_start_range:
                raise ValueError(
                    f"{self.scenario_name} does not support a fault window"
                )
            if has_severity_range:
                raise ValueError(
                    f"{self.scenario_name} does not support "
                    "fault_severity_range"
                )
            if has_fixed_severity and self.fault_severity != 0.0:
                raise ValueError(f"{self.scenario_name} must use fault_severity=0.0")
            if self.fault_duration_sim_seconds is not None:
                raise ValueError(
                    f"{self.scenario_name} does not support a fault window"
                )

    def to_json_dict(self) -> dict[str, object]:
        return {
            "scenario_name": self.scenario_name.value,
            "run_count": self.run_count,
            "fault_start_sim_seconds": self.fault_start_sim_seconds,
            "fault_start_range": (
                self.fault_start_range.to_json_dict()
                if self.fault_start_range is not None
                else None
            ),
            "fault_duration_sim_seconds": self.fault_duration_sim_seconds,
            "fault_severity": self.fault_severity,
            "fault_severity_range": (
                self.fault_severity_range.to_json_dict()
                if self.fault_severity_range is not None
                else None
            ),
        }

    @classmethod
    def from_json_dict(cls, data: dict[str, Any]) -> ScenarioRunSpec:
        fault_start_range = data.get("fault_start_range")
        fault_severity_range = data.get("fault_severity_range")
        return cls(
            scenario_name=DatasetScenario(data["scenario_name"]),
            run_count=int(data["run_count"]),
            fault_start_sim_seconds=_optional_float(
                data.get("fault_start_sim_seconds")
            ),
            fault_start_range=(
                FaultTimingRange.from_json_dict(fault_start_range)
                if fault_start_range is not None
                else None
            ),
            fault_duration_sim_seconds=_optional_float(
                data.get("fault_duration_sim_seconds")
            ),
            fault_severity=_optional_float(data.get("fault_severity")),
            fault_severity_range=(
                FaultSeverityRange.from_json_dict(fault_severity_range)
                if fault_severity_range is not None
                else None
            ),
        )


@dataclass(frozen=True)
class SplitProportions:
    """Target train/validation/test fractions of runs (not rows) per class."""

    train: float
    validation: float
    test: float

    def __post_init__(self) -> None:
        for name, value in (
            ("train", self.train),
            ("validation", self.validation),
            ("test", self.test),
        ):
            if not 0.0 <= value <= 1.0:
                raise ValueError(f"{name} proportion must be within [0.0, 1.0]")
        total = self.train + self.validation + self.test
        if abs(total - 1.0) > 1e-6:
            raise ValueError(f"split proportions must sum to 1.0 (got {total})")

    def to_json_dict(self) -> dict[str, float]:
        return {"train": self.train, "validation": self.validation, "test": self.test}

    @classmethod
    def from_json_dict(cls, data: dict[str, Any]) -> SplitProportions:
        return cls(
            train=float(data["train"]),
            validation=float(data["validation"]),
            test=float(data["test"]),
        )


@dataclass(frozen=True)
class DatasetSpec:
    """Everything needed to deterministically plan and generate one dataset.

    Immutable fields: all. `seeds` must have exactly as many entries as the
    total run count (`sum(plan.run_count for plan in scenario_plans)`) —
    seeds are consumed in `scenario_plans` order, one per planned run, so
    re-running the same spec assigns the same seed to the same run every
    time (see `run_plan.plan_runs`).

    `run_start_time` is the fixed, spec-declared anchor every planned run's
    telemetry timestamps are computed from (`run_start_time + elapsed
    simulated time`, per PR161) — never `datetime.now()`, so no wall-clock
    identity leaks into generated data.

    `sensor_noise` and `sensor_noise_regimes` are mutually exclusive
    (PR174): a spec defines either one fixed, dataset-wide noise
    configuration (`sensor_noise`, the original PR161-173 behavior) or a
    small set of named `NoiseRegime`s that each run samples one of via an
    isolated RNG stream (see `run_template.resolve_run_config`) — never
    both. Leaving both empty means no noise is applied, exactly as before
    `sensor_noise_regimes` existed.
    """

    dataset_id: str
    simulator_version: str
    scenario_plans: tuple[ScenarioRunSpec, ...]
    seeds: tuple[int, ...]
    target_asset_ids: tuple[str, ...]
    duration_sim_seconds: float
    dt_seconds: float
    run_start_time: datetime
    operating_condition_ranges: OperatingConditionRanges
    sensor_noise: tuple[SensorNoiseConfig, ...]
    split_proportions: SplitProportions
    output_directory: str
    schema_version: str = SCHEMA_VERSION
    sensor_noise_regimes: tuple[NoiseRegime, ...] = ()

    def __post_init__(self) -> None:
        if not self.dataset_id:
            raise ValueError("dataset_id must not be empty")
        if not self.simulator_version:
            raise ValueError("simulator_version must not be empty")
        if not self.scenario_plans:
            raise ValueError("scenario_plans must not be empty")
        if not self.target_asset_ids:
            raise ValueError("target_asset_ids must not be empty")
        if self.duration_sim_seconds <= 0:
            raise ValueError("duration_sim_seconds must be positive")
        if self.dt_seconds <= 0:
            raise ValueError("dt_seconds must be positive")
        if self.run_start_time.tzinfo is None:
            raise ValueError("run_start_time must be timezone-aware")
        if not self.output_directory:
            raise ValueError("output_directory must not be empty")

        if self.sensor_noise and self.sensor_noise_regimes:
            raise ValueError(
                "cannot set both sensor_noise and sensor_noise_regimes — a "
                "dataset spec must define a single fixed-or-regime-sampled "
                "sensor-noise policy"
            )
        if self.sensor_noise_regimes:
            if len(self.sensor_noise_regimes) < 2:
                raise ValueError(
                    "sensor_noise_regimes must include at least 2 regimes — "
                    "a single regime is equivalent to sensor_noise and "
                    "should use that field instead"
                )
            regime_names = [regime.name for regime in self.sensor_noise_regimes]
            if len(regime_names) != len(set(regime_names)):
                raise ValueError("sensor_noise_regimes must not repeat a name")

        scenario_names = [plan.scenario_name for plan in self.scenario_plans]
        if len(scenario_names) != len(set(scenario_names)):
            counts = Counter(scenario_names)
            duplicates = sorted(
                name.value for name, count in counts.items() if count > 1
            )
            raise ValueError(
                "scenario_plans must not repeat a scenario_name — one "
                "scenario plan should define the complete fixed-or-ranged "
                f"fault policy for that class (duplicated: {duplicates})"
            )

        for plan in self.scenario_plans:
            if (
                plan.scenario_name is not DatasetScenario.NORMAL_OPERATION
                and plan.scenario_name not in _SUPPORTED_FAULT_SCENARIOS
            ):
                raise ValueError(
                    f"unsupported scenario for dataset generation: "
                    f"{plan.scenario_name}"
                )
            if (
                plan.fault_start_range is not None
                and plan.fault_duration_sim_seconds is not None
            ):
                max_start = max(plan.fault_start_range.grid_values())
                fault_end = max_start + plan.fault_duration_sim_seconds
                if fault_end > self.duration_sim_seconds:
                    raise ValueError(
                        f"{plan.scenario_name}: fault_start_range's maximum "
                        f"grid value ({max_start}) plus "
                        f"fault_duration_sim_seconds "
                        f"({plan.fault_duration_sim_seconds}) exceeds "
                        f"duration_sim_seconds ({self.duration_sim_seconds})"
                    )

        total_runs = sum(plan.run_count for plan in self.scenario_plans)
        if len(self.seeds) != total_runs:
            raise ValueError(
                f"seeds must have exactly one entry per planned run: "
                f"{len(self.seeds)} seeds for {total_runs} planned runs"
            )

    @property
    def total_run_count(self) -> int:
        return sum(plan.run_count for plan in self.scenario_plans)

    def to_json_dict(self) -> dict[str, object]:
        return {
            "dataset_id": self.dataset_id,
            "schema_version": self.schema_version,
            "simulator_version": self.simulator_version,
            "scenario_plans": [plan.to_json_dict() for plan in self.scenario_plans],
            "seeds": list(self.seeds),
            "target_asset_ids": list(self.target_asset_ids),
            "duration_sim_seconds": self.duration_sim_seconds,
            "dt_seconds": self.dt_seconds,
            "run_start_time": self.run_start_time.isoformat(),
            "operating_condition_ranges": _ranges_to_json_dict(
                self.operating_condition_ranges
            ),
            "sensor_noise": [config.to_json_dict() for config in self.sensor_noise],
            "sensor_noise_regimes": [
                regime.to_json_dict() for regime in self.sensor_noise_regimes
            ],
            "split_proportions": self.split_proportions.to_json_dict(),
            "output_directory": self.output_directory,
        }

    @classmethod
    def from_json_dict(cls, data: dict[str, Any]) -> DatasetSpec:
        scenario_plans = tuple(
            ScenarioRunSpec.from_json_dict(entry) for entry in data["scenario_plans"]
        )
        sensor_noise = tuple(
            SensorNoiseConfig.from_json_dict(entry)
            for entry in data.get("sensor_noise", [])
        )
        sensor_noise_regimes = tuple(
            NoiseRegime.from_json_dict(entry)
            for entry in data.get("sensor_noise_regimes", [])
        )
        return cls(
            dataset_id=str(data["dataset_id"]),
            schema_version=str(data.get("schema_version", SCHEMA_VERSION)),
            simulator_version=str(data["simulator_version"]),
            scenario_plans=scenario_plans,
            seeds=tuple(int(seed) for seed in data["seeds"]),
            target_asset_ids=tuple(data["target_asset_ids"]),
            duration_sim_seconds=float(data["duration_sim_seconds"]),
            dt_seconds=float(data["dt_seconds"]),
            run_start_time=datetime.fromisoformat(str(data["run_start_time"])),
            operating_condition_ranges=_ranges_from_json_dict(
                data["operating_condition_ranges"]
            ),
            sensor_noise=sensor_noise,
            sensor_noise_regimes=sensor_noise_regimes,
            split_proportions=SplitProportions.from_json_dict(
                data["split_proportions"]
            ),
            output_directory=str(data["output_directory"]),
        )


def _optional_float(value: Any) -> float | None:
    return None if value is None else float(value)


def _ranges_to_json_dict(ranges: OperatingConditionRanges) -> dict[str, list[float]]:
    return {
        "load_baseline_percent": list(ranges.load_baseline_percent),
        "load_amplitude_percent": list(ranges.load_amplitude_percent),
        "load_period_seconds": list(ranges.load_period_seconds),
        "load_phase_radians": list(ranges.load_phase_radians),
        "initial_load_offset_percent": list(ranges.initial_load_offset_percent),
        "initial_stack_temperature_offset_celsius": list(
            ranges.initial_stack_temperature_offset_celsius
        ),
    }


def _ranges_from_json_dict(data: dict[str, Any]) -> OperatingConditionRanges:
    def _pair(key: str) -> tuple[float, float]:
        low, high = data[key]
        return float(low), float(high)

    return OperatingConditionRanges(
        load_baseline_percent=_pair("load_baseline_percent"),
        load_amplitude_percent=_pair("load_amplitude_percent"),
        load_period_seconds=_pair("load_period_seconds"),
        load_phase_radians=_pair("load_phase_radians"),
        initial_load_offset_percent=_pair("initial_load_offset_percent"),
        initial_stack_temperature_offset_celsius=_pair(
            "initial_stack_temperature_offset_celsius"
        ),
    )
