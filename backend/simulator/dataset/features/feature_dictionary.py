"""Generates `feature_dictionary.md` from the actual feature-pipeline
constants — never a hand-maintained document that can drift from the code
that produces the columns it describes."""

from __future__ import annotations

from backend.simulator.dataset.features.config import (
    DEFAULT_MEASUREMENTS,
    EXCLUDED_MEASUREMENTS,
    LONGEST_WINDOW_SECONDS,
    WINDOW_SECONDS,
    WINDOW_STATS,
)
from backend.simulator.dataset.features.exclusions import FORBIDDEN_FEATURE_FIELDS
from backend.simulator.dataset.features.residuals import RESIDUAL_SPECS
from backend.simulator.dataset.features.schema import METADATA_COLUMNS

_STAT_FORMULAS = {
    "mean": "arithmetic mean of the window's values",
    "std": "population standard deviation of the window's values",
    "min": "minimum value in the window",
    "max": "maximum value in the window",
    "slope": "ordinary-least-squares slope of value vs. elapsed_sim_seconds "
    "within the window, in value-units per second",
    "delta": "current sample's value minus the window's oldest sample's value",
}


def render_feature_dictionary(efficiency_clamp_stats: dict[str, object]) -> str:
    lines: list[str] = []
    lines.append("# Feature Dictionary — `pem-faults-pilot-features`")
    lines.append("")
    lines.append(
        "Generated by `backend/simulator/dataset/features/feature_dictionary.py` "
        "directly from the feature-pipeline's own constants — this file cannot "
        "drift from the code that produces `features.parquet`."
    )
    lines.append("")

    lines.append("## Feature-row unit")
    lines.append("")
    lines.append(
        "One row per (`simulation_run_id`, `asset_id`, `timestamp`) — one asset, "
        "one sample time, using only telemetry available at or before that "
        "timestamp. Labels are joined separately from `labels.parquet` on "
        "`(simulation_run_id, asset_id, timestamp)`, never embedded in "
        "`features.parquet`."
    )
    lines.append("")

    lines.append("## Metadata columns (`features.parquet`, never model features)")
    lines.append("")
    for column in METADATA_COLUMNS:
        lines.append(f"- `{column}`")
    lines.append("")

    lines.append("## Trailing-window convention")
    lines.append("")
    lines.append(
        "For a window of length `W` seconds, a row's window is every observation "
        "with `current_timestamp - W < observation_timestamp <= current_timestamp` "
        "— trailing, never centered, never including a sample after the current "
        "one. Windows: " + ", ".join(f"{w}s" for w in WINDOW_SECONDS) + "."
    )
    lines.append("")
    lines.append(
        f"**Warm-up policy**: a feature row requires the longest window "
        f"({LONGEST_WINDOW_SECONDS}s) to be fully populated — rows before the "
        f"{LONGEST_WINDOW_SECONDS}s mark in each `(run, asset)` series are dropped "
        "entirely rather than partially computed. The first eligible "
        f"`elapsed_sim_seconds` in every run is **{LONGEST_WINDOW_SECONDS}.0**."
    )
    lines.append("")

    lines.append("## Selected measurements")
    lines.append("")
    for measurement in DEFAULT_MEASUREMENTS:
        lines.append(f"- `{measurement}`")
    lines.append("")
    lines.append(
        f"**Excluded**: `{', '.join(EXCLUDED_MEASUREMENTS)}` — retained in "
        "`telemetry.parquet` (this pipeline never touches dataset generation) "
        "but excluded from the default feature set. Evidence from this "
        f"generation run's feature-eligible rows: {efficiency_clamp_stats}."
    )
    lines.append("")

    lines.append("## Per-measurement current-sample features")
    lines.append("")
    lines.append("For every selected measurement `M`:")
    lines.append("")
    lines.append("| Feature | Formula |")
    lines.append("|---|---|")
    lines.append("| `M` | the raw observed value at the current sample |")
    lines.append(
        "| `M__diff_10s` | current sample's value minus the immediately "
        "preceding sample's value (one 10s step) |"
    )
    lines.append(
        "| `M__roc_per_s` | `M__diff_10s / 10.0` — rate of change per second |"
    )
    lines.append("")

    lines.append("## Trailing-window statistics")
    lines.append("")
    lines.append(
        "For every selected measurement `M` and window `Ws` in {30s, 60s, 120s}:"
    )
    lines.append("")
    lines.append("| Feature | Formula |")
    lines.append("|---|---|")
    for stat in WINDOW_STATS:
        lines.append(f"| `M__{stat}_Ws` | {_STAT_FORMULAS[stat]} |")
    lines.append("")

    lines.append("## Cross-signal features")
    lines.append("")
    lines.append(
        "| Feature | Formula | Units | Interpretation | Zero-denominator "
        "behavior | Duplicates an emitted measurement? |"
    )
    lines.append("|---|---|---|---|---|---|")
    lines.append(
        "| `voltage_per_current` | `voltage / current` | V/A | "
        "internal-resistance-scale quantity; shifts under hydrogen starvation's "
        "added voltage droop | null when \\|current\\| < 1e-6 (never inf/nan) | No |"
    )
    lines.append(
        "| `power_per_fuel_flow` | `power_output / fuel_flow` | kW/SLPM | "
        "unclamped analogue of the emitted `efficiency` channel — retains spread "
        "`efficiency` loses to its 100% clamp | null when \\|fuel_flow\\| < 1e-6 "
        "(never inf/nan) | No — see `cross_signal.py` for why this is "
        "deliberately *not* a reintroduction of `efficiency` |"
    )
    lines.append("")
    lines.append(
        "Considered and **not** shipped: `power_error` (duplicates `power_output` "
        "by construction, ~0 by definition — see `cross_signal.py`); "
        "`temperature_per_current` (not a physically meaningful ratio — "
        "`stack_temperature` has a large additive offset at zero load)."
    )
    lines.append("")

    lines.append("## Physics-informed residual features")
    lines.append("")
    lines.append(
        "`residual = observed_measurement - expected_healthy(current)`, where "
        "`expected_healthy` is a **fixed, documented reference curve** (Plant "
        "Alpha's own rated/healthy constants — see `residuals.py`'s module "
        "docstring), never fit from training data and never reading hidden "
        "simulator state."
    )
    lines.append("")
    residual_formulas = {
        "voltage__healthy_residual": "voltage - (0.78 - (current/200.0)*0.06)",
        "fuel_flow__healthy_residual": "fuel_flow - (1.5 + (current/200.0)*1.0)",
        "stack_temperature__healthy_residual": (
            "stack_temperature - (55.0 + (current/200.0)*20.0 - 0.5)"
        ),
        "coolant_flow__healthy_residual": "coolant_flow - (8.0 + (current/200.0)*18.0)",
    }
    lines.append("| Feature | Reference formula |")
    lines.append("|---|---|")
    for spec in RESIDUAL_SPECS:
        lines.append(f"| `{spec.name}` | `{residual_formulas[spec.name]}` |")
    lines.append("")
    lines.append(
        "**Deferred to a future PR**: any residual whose reference curve would "
        "need to be *fit* (e.g. regression-calibrated against this dataset's own "
        "`normal_operation` runs, training-split-only) rather than a fixed "
        "constant — see `residuals.py`'s module docstring."
    )
    lines.append("")

    lines.append("## `labels.parquet`")
    lines.append("")
    lines.append(
        "One row per feature-eligible `(simulation_run_id, asset_id, timestamp)` "
        "— exactly the same key set as `features.parquet`, so the two tables "
        "join 1:1."
    )
    lines.append("")
    lines.append("| Column | Description |")
    lines.append("|---|---|")
    lines.append("| `simulation_run_id` | Join key |")
    lines.append("| `asset_id` | Join key |")
    lines.append("| `timestamp` | Join key |")
    lines.append(
        "| `split` | `train`/`validation`/`test`, inherited from the source "
        "dataset's `splits.json` |"
    )
    lines.append(
        "| `class_label` | The **per-row derived** target: `healthy` unless "
        "this exact asset/timestamp falls inside an *active* fault window, in "
        "which case `cooling_degradation`/`hydrogen_supply_issue`/"
        "`sensor_anomaly` — derived from `ground_truth.parquet`'s "
        "`fault_active`/`fault_type`/`sensor_corruption_type`, **never** from "
        "`runs.parquet`'s configured `class_label` (which is constant for the "
        "whole run regardless of fault timing or target asset). "
        "See `labels.py`. |"
    )
    lines.append(
        '| `is_anomalous` | `class_label != "healthy"` — derived secondary '
        "binary target |"
    )
    lines.append(
        "| `fault_severity` | Evaluation-only instantaneous ground-truth "
        "severity; null when healthy. **Never a model feature.** |"
    )
    lines.append("")

    lines.append("## Forbidden model-feature fields")
    lines.append("")
    lines.append(
        "Enforced automatically by `exclusions.assert_no_forbidden_features` at "
        "generation time — never only by caller discipline:"
    )
    lines.append("")
    for field in sorted(FORBIDDEN_FEATURE_FIELDS):
        lines.append(f"- `{field}`")
    lines.append("")

    return "\n".join(lines) + "\n"
