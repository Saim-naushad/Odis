"""Builds `robust_evaluation_report.md` from already-computed results — no
computation happens here (mirrors `ood/report.py`'s own split from
`generate.py`)."""

from __future__ import annotations

from backend.simulator.dataset.robustness.artifacts import ModelArtifacts
from backend.simulator.dataset.robustness.comparison import CohortComparison
from backend.simulator.dataset.robustness.config import EXTERNAL_COHORT_NAMES
from backend.simulator.dataset.robustness.evaluation import CohortEvaluation
from backend.simulator.dataset.robustness.promotion import PromotionDecision


def _fmt(value: float | None, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    return f"{value:.{digits}f}"


def _model_line(label: str, artifacts: ModelArtifacts) -> str:
    meta = artifacts.model_metadata
    return (
        f"- **{label}**: `{meta['model_type']}` / feature group "
        f"`{meta['feature_group']}` / hyperparameters `{meta['hyperparameters']}` "
        f"/ trained on `{meta['source_dataset_id']}`"
    )


def _comparison_row(cohort_name: str, comparison: CohortComparison) -> str:
    ba = comparison.balanced_accuracy
    fa = comparison.false_alert_events_per_healthy_hour
    missed = comparison.correct_class_missed_run_count
    return (
        f"| {cohort_name} | {_fmt(ba.original_value)} | {_fmt(ba.robust_value)} | "
        f"{_fmt(ba.absolute_change)} | {_fmt(fa.original_value)} | "
        f"{_fmt(fa.robust_value)} | {_fmt(missed.original_value, 0)} | "
        f"{_fmt(missed.robust_value, 0)} |"
    )


def _per_class_recall_section(cohort_name: str, comparison: CohortComparison) -> str:
    lines = [f"**{cohort_name} — per-class recall (original -> robust)**", ""]
    lines.append("| class | original | robust | change |")
    lines.append("|---|---|---|---|")
    for cls, delta in comparison.per_class_recall.items():
        lines.append(
            f"| {cls} | {_fmt(delta.original_value)} | {_fmt(delta.robust_value)} | "
            f"{_fmt(delta.absolute_change)} |"
        )
    return "\n".join(lines)


def render_evaluation_report(
    *,
    generation_command: str,
    original_artifacts: ModelArtifacts,
    robust_artifacts: ModelArtifacts,
    internal_original: CohortEvaluation,
    internal_robust: CohortEvaluation,
    cohort_comparisons: dict[str, CohortComparison],
    decision: PromotionDecision,
) -> str:
    lines: list[str] = []
    lines.append("# PR174 Robustness-Training Evaluation Report")
    lines.append("")
    lines.append(f"Generated by: `{generation_command}`")
    lines.append("")
    lines.append("## Models compared")
    lines.append("")
    lines.append(_model_line("Original (PR168)", original_artifacts))
    lines.append(_model_line("Robust candidate (PR174)", robust_artifacts))
    lines.append("")

    lines.append("## Internal test results")
    lines.append("")
    lines.append("| model | test cohort | balanced accuracy | healthy FPR |")
    lines.append("|---|---|---|---|")
    lines.append(
        "| original | pilot test split | "
        f"{_fmt(internal_original.diagnosis.multiclass_metrics.balanced_accuracy)} | "
        f"{_fmt(internal_original.diagnosis.healthy_false_positive_rate)} |"
    )
    lines.append(
        "| robust | robust-training test split | "
        f"{_fmt(internal_robust.diagnosis.multiclass_metrics.balanced_accuracy)} | "
        f"{_fmt(internal_robust.diagnosis.healthy_false_positive_rate)} |"
    )
    lines.append("")

    lines.append("## Original vs. robust — diagnosis (balanced accuracy)")
    lines.append("")
    lines.append(
        "| cohort | original BA | robust BA | change | original false-alerts/hr | "
        "robust false-alerts/hr | original missed runs | robust missed runs |"
    )
    lines.append("|---|---|---|---|---|---|---|---|")
    for name in EXTERNAL_COHORT_NAMES:
        lines.append(_comparison_row(name, cohort_comparisons[name]))
    lines.append("")

    lines.append("## Per-class recall by cohort")
    lines.append("")
    for name in EXTERNAL_COHORT_NAMES:
        lines.append(_per_class_recall_section(name, cohort_comparisons[name]))
        lines.append("")

    lines.append("## Alert behavior detail")
    lines.append("")
    lines.append(
        "| cohort | healthy runs w/ alert (orig -> robust) | median latency s "
        "(orig -> robust) | detected<=60s (orig -> robust) | detected<=120s "
        "(orig -> robust) | detected<=240s (orig -> robust) |"
    )
    lines.append("|---|---|---|---|---|---|")
    for name in EXTERNAL_COHORT_NAMES:
        c = cohort_comparisons[name]
        lines.append(
            f"| {name} | {_fmt(c.healthy_runs_with_alert_count.original_value, 0)} "
            f"-> {_fmt(c.healthy_runs_with_alert_count.robust_value, 0)} | "
            f"{_fmt(c.median_correct_class_latency_seconds.original_value)} -> "
            f"{_fmt(c.median_correct_class_latency_seconds.robust_value)} | "
            f"{_fmt(c.detected_within_60s.original_value)} -> "
            f"{_fmt(c.detected_within_60s.robust_value)} | "
            f"{_fmt(c.detected_within_120s.original_value)} -> "
            f"{_fmt(c.detected_within_120s.robust_value)} | "
            f"{_fmt(c.detected_within_240s.original_value)} -> "
            f"{_fmt(c.detected_within_240s.robust_value)} |"
        )
    lines.append("")

    lines.append("## Promotion decision")
    lines.append("")
    lines.append(f"**{decision.decision}**")
    lines.append("")
    lines.append("Reasons:")
    for reason in decision.reasons:
        lines.append(f"- {reason}")
    lines.append("")
    lines.append("Thresholds applied (fixed before reading these results):")
    lines.append("")
    for key, value in decision.thresholds.to_json_dict().items():
        lines.append(f"- `{key}` = `{value}`")
    lines.append("")

    return "\n".join(lines)
