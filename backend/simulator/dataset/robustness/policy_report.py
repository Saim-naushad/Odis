"""Builds `robust_promotion_report.md` and the four required PR175 plots
from already-computed results — no computation happens here (mirrors
`report.py`/`alert_policy/plots.py`'s own split from their `generate.py`).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from backend.simulator.dataset.alert_policy.state_machine import StateMachineConfig
from backend.simulator.dataset.robustness.candidate import FrozenCandidate
from backend.simulator.dataset.robustness.comparison import CohortComparison
from backend.simulator.dataset.robustness.evaluation import CohortEvaluation
from backend.simulator.dataset.robustness.policy_promotion import (
    PolicyPromotionDecision,
)
from backend.simulator.dataset.robustness.policy_search import RobustPolicySearchResult

REQUIRED_COHORT_NAMES: tuple[str, ...] = (
    "robust_internal_test",
    "pilot",
    "high_load",
    "hot_start",
    "late_onset",
    "high_noise",
    "combined_ood_v1",
)

try:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    MATPLOTLIB_AVAILABLE = True
except ImportError:  # pragma: no cover - exercised only without the extra
    MATPLOTLIB_AVAILABLE = False


@dataclass(frozen=True)
class PlotResult:
    filename: str
    title: str
    caption: str


def _fmt(value: float | None, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    return f"{value:.{digits}f}"


def _system_row(name: str, system: dict[str, CohortEvaluation]) -> str:
    e = system[name]
    return (
        f"| {name} | "
        f"{_fmt(e.diagnosis.multiclass_metrics.balanced_accuracy)} | "
        f"{_fmt(e.diagnosis.multiclass_metrics.macro_f1)} | "
        f"{_fmt(e.alerts.false_alerts.false_alert_events_per_healthy_hour)} | "
        f"{len(e.alerts.false_alerts.healthy_run_ids_with_alert)} | "
        f"{_fmt(e.alerts.false_alerts.mean_false_episode_duration_seconds)} | "
        f"{len(e.alerts.detection.correct_class_missed_runs)} | "
        f"{len(e.alerts.detection.any_fault_missed_runs)} | "
        f"{_fmt(e.alerts.detection.median_correct_class_latency_seconds)} | "
        f"{_fmt(e.alerts.detection.detected_within_seconds(60), 2)} | "
        f"{_fmt(e.alerts.detection.detected_within_seconds(120), 2)} | "
        f"{_fmt(e.alerts.detection.detected_within_seconds(240), 2)} | "
        f"{e.alerts.incorrect_class_alert_run_count} | "
        f"{_fmt(e.availability.insufficient_data_rate, 4)} |"
    )


_SYSTEM_TABLE_HEADER = (
    "| cohort | balanced accuracy | macro F1 | false alerts/hr | healthy runs "
    "affected | false-alert duration (s) | correct-class missed | any-fault "
    "missed | median latency (s) | detected<=60s | detected<=120s | "
    "detected<=240s | incorrect-class alerts | insufficient-data rate |"
)
_SYSTEM_TABLE_DIVIDER = "|" + "---|" * 14


def render_policy_evaluation_report(
    *,
    generation_command: str,
    candidate: FrozenCandidate,
    selected_policy: StateMachineConfig,
    policy_search_result: RobustPolicySearchResult,
    system_a: dict[str, CohortEvaluation],
    system_b: dict[str, CohortEvaluation],
    system_c: dict[str, CohortEvaluation],
    b_vs_a: dict[str, CohortComparison],
    c_vs_a: dict[str, CohortComparison],
    decision: PolicyPromotionDecision,
) -> str:
    lines: list[str] = []
    lines.append("# PR175 Robust Candidate Alert-Policy Selection and Promotion")
    lines.append("")
    lines.append(f"Generated by: `{generation_command}`")
    lines.append("")

    lines.append("## Candidate")
    lines.append("")
    meta = candidate.model_metadata
    lines.append(
        f"- `{meta['model_type']}` / feature group `{candidate.feature_group}` / "
        f"hyperparameters `{meta['hyperparameters']}` / trained on "
        f"`{meta['source_dataset_id']}`"
    )
    lines.append(f"- candidate pipeline sha256: `{candidate.pipeline_sha256}`")
    lines.append("")

    lines.append("## Policy search (validation split only)")
    lines.append("")
    lines.append(f"- selection rule: {policy_search_result.selection_rule}")
    baseline_latency = _fmt(policy_search_result.baseline_median_latency_seconds)
    lines.append(
        "- baseline median correct-class latency (robust model + PR170 policy, "
        f"validation split): {baseline_latency}s"
    )
    lines.append(f"- candidates evaluated: {len(policy_search_result.candidates)}")
    survivors = sum(1 for c in policy_search_result.candidates if not c.rejected)
    lines.append(f"- candidates surviving rejection: {survivors}")
    lines.append("")
    lines.append("## Selected policy (PR175)")
    lines.append("")
    lines.append(f"- entry probability: {selected_policy.entry_probability}")
    lines.append(f"- entry persistence: {selected_policy.entry_persistence}")
    lines.append(
        f"- healthy exit probability: {selected_policy.healthy_exit_probability}"
    )
    lines.append(f"- exit persistence: {selected_policy.exit_persistence}")
    lines.append("")

    lines.append("## Three-system comparison")
    lines.append("")
    lines.append(
        "System A = original PR168 model + PR170 policy; System B = robust "
        "PR174 candidate + PR170 policy (unchanged); System C = robust PR174 "
        "candidate + this PR's newly selected policy. B and C share identical "
        "row-level diagnosis by construction (asserted in code)."
    )
    lines.append("")
    for label, system in (
        ("System A (original + PR170 policy)", system_a),
        ("System B (robust + PR170 policy)", system_b),
        ("System C (robust + PR175 policy)", system_c),
    ):
        lines.append(f"### {label}")
        lines.append("")
        lines.append(_SYSTEM_TABLE_HEADER)
        lines.append(_SYSTEM_TABLE_DIVIDER)
        for name in REQUIRED_COHORT_NAMES:
            if name in system:
                lines.append(_system_row(name, system))
        lines.append("")

    lines.append("## C vs. A — balanced-accuracy and false-alert deltas")
    lines.append("")
    lines.append(
        "| cohort | A balanced accuracy | C balanced accuracy | change | "
        "A false-alerts/hr | C false-alerts/hr |"
    )
    lines.append("|---|---|---|---|---|---|")
    for name in REQUIRED_COHORT_NAMES:
        if name not in c_vs_a:
            continue
        c = c_vs_a[name]
        ba = c.balanced_accuracy
        fa = c.false_alert_events_per_healthy_hour
        lines.append(
            f"| {name} | {_fmt(ba.original_value)} | {_fmt(ba.robust_value)} | "
            f"{_fmt(ba.absolute_change)} | {_fmt(fa.original_value)} | "
            f"{_fmt(fa.robust_value)} |"
        )
    lines.append("")

    lines.append("## Promotion decision")
    lines.append("")
    lines.append(f"**{decision.decision}**")
    lines.append("")
    lines.append("Reasons:")
    for reason in decision.reasons:
        lines.append(f"- {reason}")
    lines.append("")
    lines.append("Thresholds applied (fixed before reading these results):")
    lines.append("")
    for key, value in decision.thresholds.to_json_dict().items():
        lines.append(f"- `{key}` = `{value}`")
    lines.append("")

    return "\n".join(lines)


def generate_policy_plots(
    *,
    policy_search_result: RobustPolicySearchResult,
    system_a: dict[str, CohortEvaluation],
    system_b: dict[str, CohortEvaluation],
    system_c: dict[str, CohortEvaluation],
    output_dir: Path,
) -> list[PlotResult]:
    if not MATPLOTLIB_AVAILABLE:
        return []

    output_dir.mkdir(parents=True, exist_ok=True)
    plots: list[PlotResult] = []

    # 1. policy_false_alarm_latency_tradeoff.png
    fig, ax = plt.subplots(figsize=(7, 5))
    survivors = [c for c in policy_search_result.candidates if not c.rejected]
    rejected = [c for c in policy_search_result.candidates if c.rejected]
    for group, color, label in (
        (rejected, "lightgray", "rejected"),
        (survivors, "tab:blue", "survived"),
    ):
        latencies = [
            c.median_correct_class_latency_seconds
            for c in group
            if c.median_correct_class_latency_seconds is not None
        ]
        rates = [
            c.false_alert_events_per_healthy_hour
            for c in group
            if c.median_correct_class_latency_seconds is not None
        ]
        ax.scatter(latencies, rates, color=color, label=label, alpha=0.7, s=20)
    selected_latency = (
        policy_search_result.selected.median_correct_class_latency_seconds
        if policy_search_result.selected is not None
        else None
    )
    if policy_search_result.selected is not None and selected_latency is not None:
        s = policy_search_result.selected
        ax.scatter(
            [selected_latency],
            [s.false_alert_events_per_healthy_hour],
            color="tab:red",
            marker="*",
            s=200,
            label="selected",
            zorder=5,
        )
    ax.set_xlabel("median correct-class latency (s)")
    ax.set_ylabel("false alert events / healthy hour")
    ax.set_title("Policy search: false-alarm/latency tradeoff (validation)")
    ax.legend()
    filename = "policy_false_alarm_latency_tradeoff.png"
    fig.tight_layout()
    fig.savefig(output_dir / filename, dpi=120)
    plt.close(fig)
    plots.append(
        PlotResult(
            filename=filename,
            title="Policy search: false-alarm/latency tradeoff",
            caption=(
                "Every grid candidate's validation false-alert rate vs. median "
                "correct-class latency; the selected policy is starred."
            ),
        )
    )

    cohort_names = [name for name in REQUIRED_COHORT_NAMES if name in system_a]

    # 2. system_comparison_by_cohort.png
    fig, ax = plt.subplots(figsize=(9, 5))
    x = range(len(cohort_names))
    width = 0.25
    for offset, (system, label, color) in enumerate(
        (
            (system_a, "A: original + PR170", "tab:gray"),
            (system_b, "B: robust + PR170", "tab:orange"),
            (system_c, "C: robust + PR175", "tab:green"),
        )
    ):
        values = [
            system[name].diagnosis.multiclass_metrics.balanced_accuracy
            for name in cohort_names
        ]
        ax.bar(
            [i + (offset - 1) * width for i in x],
            values,
            width=width,
            label=label,
            color=color,
        )
    ax.set_xticks(list(x))
    ax.set_xticklabels(cohort_names, rotation=30, ha="right")
    ax.set_ylabel("balanced accuracy")
    ax.set_title("System comparison by cohort (row-level balanced accuracy)")
    ax.legend()
    filename = "system_comparison_by_cohort.png"
    fig.tight_layout()
    fig.savefig(output_dir / filename, dpi=120)
    plt.close(fig)
    plots.append(
        PlotResult(
            filename=filename,
            title="System comparison by cohort",
            caption="Row-level balanced accuracy for Systems A/B/C on every cohort.",
        )
    )

    # 3. healthy_run_alerts_by_cohort.png
    fig, ax = plt.subplots(figsize=(9, 5))
    for offset, (system, label, color) in enumerate(
        (
            (system_a, "A: original + PR170", "tab:gray"),
            (system_b, "B: robust + PR170", "tab:orange"),
            (system_c, "C: robust + PR175", "tab:green"),
        )
    ):
        values = [
            len(system[name].alerts.false_alerts.healthy_run_ids_with_alert)
            for name in cohort_names
        ]
        ax.bar(
            [i + (offset - 1) * width for i in x],
            values,
            width=width,
            label=label,
            color=color,
        )
    ax.set_xticks(list(x))
    ax.set_xticklabels(cohort_names, rotation=30, ha="right")
    ax.set_ylabel("healthy runs affected")
    ax.set_title("Healthy runs affected by a false alert, by cohort")
    ax.legend()
    filename = "healthy_run_alerts_by_cohort.png"
    fig.tight_layout()
    fig.savefig(output_dir / filename, dpi=120)
    plt.close(fig)
    plots.append(
        PlotResult(
            filename=filename,
            title="Healthy runs affected by cohort",
            caption="Count of healthy runs with at least one false alert episode.",
        )
    )

    # 4. detection_latency_by_cohort.png
    fig, ax = plt.subplots(figsize=(9, 5))
    for offset, (system, label, color) in enumerate(
        (
            (system_a, "A: original + PR170", "tab:gray"),
            (system_b, "B: robust + PR170", "tab:orange"),
            (system_c, "C: robust + PR175", "tab:green"),
        )
    ):
        values = [
            system[name].alerts.detection.median_correct_class_latency_seconds or 0.0
            for name in cohort_names
        ]
        ax.bar(
            [i + (offset - 1) * width for i in x],
            values,
            width=width,
            label=label,
            color=color,
        )
    ax.set_xticks(list(x))
    ax.set_xticklabels(cohort_names, rotation=30, ha="right")
    ax.set_ylabel("median correct-class latency (s)")
    ax.set_title("Detection latency by cohort")
    ax.legend()
    filename = "detection_latency_by_cohort.png"
    fig.tight_layout()
    fig.savefig(output_dir / filename, dpi=120)
    plt.close(fig)
    plots.append(
        PlotResult(
            filename=filename,
            title="Detection latency by cohort",
            caption="Median correct-class detection latency for Systems A/B/C.",
        )
    )

    return plots
